import * as THREE from 'three';
import { RoomEnvironment } from 'three/examples/jsm/environments/RoomEnvironment.js';
import { CARS, defaultConfig } from './vehicle/carDefs.js';
import { buildCarModel } from './vehicle/carModel.js';
const q = new URLSearchParams(location.search);
const r = new THREE.WebGLRenderer({ antialias: true });
r.setSize(innerWidth, innerHeight);
r.toneMapping = THREE.ACESFilmicToneMapping; r.toneMappingExposure = 0.9;
document.body.appendChild(r.domElement);
const scene = new THREE.Scene();
scene.background = new THREE.Color(0x30363c);
scene.environment = new THREE.PMREMGenerator(r).fromScene(new RoomEnvironment(), 0.04).texture;
scene.add(new THREE.DirectionalLight(0xffffff, 2).translateY(10).translateX(5));
const ids = (q.get('ids') || CARS.map((c) => c.id).join(',')).split(',');
const view = q.get('view') || 'side';
ids.forEach((id, k) => {
  const car = CARS.find((c) => c.id === id);
  const cfg = defaultConfig(car);
  if (q.has('liv')) cfg.livery = q.get('liv');
  const m = buildCarModel(car, cfg);
  const zf = m.zf, zr = m.zr;
  m.wheels.forEach((w, i) => { const tw = car.body.W - car.body.RW * 0.95; w.holder.position.set((i % 2 ? 1 : -1) * tw / 2, car.body.R, i < 2 ? zf : zr); });
  const cols = Math.min(4, ids.length);
  m.root.position.set((k % cols) * 7, 0, Math.floor(k / cols) * 7);
  m.root.rotation.y = view === 'side' ? Math.PI / 2 : view === 'front' ? 0 : 0.7;
  scene.add(m.root);
});
const cols = Math.min(4, ids.length), rows = Math.ceil(ids.length / cols);
const cam = new THREE.PerspectiveCamera(30, innerWidth / innerHeight, 0.1, 500);
const cx = (cols - 1) * 7 / 2, cz = (rows - 1) * 7 / 2;
cam.position.set(cx + (view === 'side' ? 0 : 4), 6 + rows * 3, cz + 10 + rows * 6);
cam.lookAt(cx, 0.5, cz);
r.render(scene, cam);
window.__status = { ok: true };
